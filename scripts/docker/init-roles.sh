#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    DO \$\$
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${FLYWAY_USER}') THEN
        CREATE ROLE ${FLYWAY_USER} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '${FLYWAY_PASSWORD}';
      ELSE
        ALTER ROLE ${FLYWAY_USER} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '${FLYWAY_PASSWORD}';
      END IF;
      IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${DB_USER}') THEN
        CREATE ROLE ${DB_USER} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '${DB_PASSWORD}';
      ELSE
        ALTER ROLE ${DB_USER} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '${DB_PASSWORD}';
      END IF;
    END
    \$\$;

    REVOKE ALL ON DATABASE "${POSTGRES_DB}" FROM PUBLIC;
    GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO ${FLYWAY_USER}, ${DB_USER};

    REVOKE CREATE ON SCHEMA public FROM PUBLIC;
    GRANT USAGE, CREATE ON SCHEMA public TO ${FLYWAY_USER};
    GRANT USAGE ON SCHEMA public TO ${DB_USER};

    ALTER DEFAULT PRIVILEGES FOR ROLE ${FLYWAY_USER} IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${DB_USER};
    ALTER DEFAULT PRIVILEGES FOR ROLE ${FLYWAY_USER} IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ${DB_USER};

    CREATE EXTENSION IF NOT EXISTS pgcrypto;

    -- Note: Table-specific privilege hardening on public.audit_logs (REVOKE ALL, GRANT SELECT, INSERT)
    -- is automatically executed by Flyway's afterMigrate__audit_logs_privileges.sql callback in backend migrations.
EOSQL
